#!/usr/bin/env node
/**
 * Copies the icon set from machvive-chat-syncopation into src/conductor/icons.js,
 * and writes the same set as src/icons.css for pages that want it as pure CSS.
 *
 * The two packages draw the same icons, and syncopation is where icons are
 * added: drop the Material Symbols files into its design/icons/ and run its
 * build-icons.mjs, then run this here.
 *
 *   npm run sync-icons                       # from ../machvive-chat-syncopation-ai
 *   npm run sync-icons -- path/to/icons.js   # from somewhere else
 *   npm run sync-icons -- --check            # exit 1 if out of date, change nothing
 *   npm run sync-icons -- --check --if-present   # the same, but skip if there is no source
 *
 * `npm version` runs the last form first (the `preversion` script), so a
 * release cannot go out behind syncopation. It checks rather than writes:
 * `npm version` commits only package.json, so regenerated files would be left
 * out of the tagged commit. `--if-present` is for a checkout without
 * syncopation beside it; the suite still checks icons.css against icons.js.
 *
 * The source is read as text and never imported, so nothing in the other
 * repository runs. Only the ICONS block of icons.js is rewritten; the rest of
 * the module is this package's own. icons.css is generated whole.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DEFAULT_SOURCE = new URL(
  '../../machvive-chat-syncopation-ai/src/wc/machvive-chat-syncopation-services/icons.js',
  import.meta.url);
const TARGET = new URL('../src/conductor/icons.js', import.meta.url);
const STYLESHEET = new URL('../src/icons.css', import.meta.url);

/**
 * Names that would collide with a property the stylesheet or `<neodigm-icon>`
 * already uses: an icon called `size` would be `--n55-icon-size`.
 */
const RESERVED = new Set(['size']);

const OPEN = 'export const ICONS = Object.freeze({\n';
const CLOSE = '\n});';

/**
 * Reads `--mcs-icon-<name>: url("…");` declarations from syncopation's module.
 * Refuses anything that could not be a plain data-URI SVG, since it ends up
 * inside a JavaScript string and a CSS value.
 *
 * @param {string} source
 * @returns {Array<[string, string]>} sorted by name
 */
export function readIcons(source) {
  const icons = [...source.matchAll(/--mcs-icon-([a-z0-9-]+): (url\("[^"\n]*"\));/g)]
    .map(([, name, url]) => [name, url]);
  if (icons.length === 0) throw new Error('no --mcs-icon-* declarations found');
  for (const [name, url] of icons) {
    if (!/^url\("data:image\/svg\+xml,[^"#`$\\]+"\)$/.test(url)) {
      throw new Error(`${name}: not a data-URI SVG this script can copy safely`);
    }
  }
  const names = icons.map(([name]) => name);
  if (new Set(names).size !== names.length) throw new Error('an icon is declared twice');
  const clash = names.find((name) => RESERVED.has(name));
  if (clash) throw new Error(`an icon cannot be called "${clash}": --n55-icon-${clash} is already a setting`);
  return icons.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/**
 * The target module with its ICONS block replaced.
 *
 * @param {string} target
 * @param {Array<[string, string]>} icons
 */
export function writeIcons(target, icons) {
  const start = target.indexOf(OPEN);
  const end = target.indexOf(CLOSE, start);
  if (start === -1 || end === -1) throw new Error('no ICONS block in the target');
  const body = icons.map(([name, url]) => `  '${name}': ${JSON.stringify(url)}`).join(',\n');
  return target.slice(0, start + OPEN.length) + body + target.slice(end);
}

/**
 * The set as a stylesheet: one custom property per icon on :root, and classes
 * that draw one on any element. Generated whole, never edited by hand.
 *
 * @param {Array<[string, string]>} icons
 */
export function stylesheet(icons) {
  return `/*
 * Neodigm 55 icons, as pure CSS. No JavaScript, no font, no component.
 *
 * GENERATED by \`npm run sync-icons\` from the same set as src/conductor/icons.js.
 * Do not edit: a test fails if this file and that set disagree.
 *
 * Google Material Symbols (Outlined, 24dp, weight 400, unfilled), Apache-2.0.
 *
 * Each icon is a custom property holding a data-URI SVG:
 *
 *   mask-image: var(--n55-icon-search);        recolourable, takes currentColor
 *   background-image: var(--n55-icon-search);  as is, always black
 *
 * Or the classes: <span class="n55-icon n55-icon-search"></span>.
 * Size with --n55-icon-size (default 24px). Redefine any --n55-icon-<name>
 * after this file to replace an icon, or define a new one to add it.
 */
:root {
${icons.map(([name, url]) => `  --n55-icon-${name}: ${url};`).join('\n')}
}

.n55-icon {
  display: inline-block;
  inline-size: var(--n55-icon-size, 24px);
  block-size: var(--n55-icon-size, 24px);
  vertical-align: middle;
  flex: none;
  background-color: currentColor;
  -webkit-mask: var(--n55-glyph, linear-gradient(transparent, transparent)) center / contain no-repeat;
  mask: var(--n55-glyph, linear-gradient(transparent, transparent)) center / contain no-repeat;
}
${icons.map(([name]) => `.n55-icon-${name} { --n55-glyph: var(--n55-icon-${name}); }`).join('\n')}
`;
}

/** Names in one list and not the other. */
export function difference(before, after) {
  const was = new Set(before);
  const now = new Set(after);
  return {
    added: after.filter((n) => !was.has(n)),
    removed: before.filter((n) => !now.has(n))
  };
}

/**
 * The command line. Returns the exit code: 0 done or in step, 1 out of date
 * under --check. Throws on a source it cannot read or trust.
 *
 * @param {string[]} args
 */
export function main(args) {
  const check = args.includes('--check');
  const path = args.find((a) => !a.startsWith('--'));
  const source = path ? new URL(path, pathToFileURL(`${process.cwd()}/`)) : DEFAULT_SOURCE;
  if (args.includes('--if-present') && !existsSync(source)) {
    console.log(`sync-icons: no source at ${fileURLToPath(source)}, so not checked`);
    return 0;
  }

  const icons = readIcons(readFileSync(source, 'utf8'));
  const before = readFileSync(TARGET, 'utf8');
  const after = writeIcons(before, icons);
  let sheetBefore = '';
  try { sheetBefore = readFileSync(STYLESHEET, 'utf8'); } catch { /* first run */ }
  const sheet = stylesheet(icons);
  const oldNames = [...before.matchAll(/^ {2}'([a-z0-9-]+)': /gm)].map(([, n]) => n);
  const { added, removed } = difference(oldNames, icons.map(([n]) => n));

  console.log(`${icons.length} icons in ${fileURLToPath(source)}`);
  if (added.length) console.log(`  added:   ${added.join(', ')}`);
  if (removed.length) console.log(`  removed: ${removed.join(', ')}`);
  if (after === before && sheet === sheetBefore) { console.log('  already in step'); return 0; }
  if (check) { console.log('  out of date: run npm run sync-icons'); return 1; }
  writeFileSync(TARGET, after);
  writeFileSync(STYLESHEET, sheet);
  console.log(`  wrote ${fileURLToPath(TARGET)}`);
  console.log(`  wrote ${fileURLToPath(STYLESHEET)}`);
  if (removed.length) console.log('  removed icons break pages that name them: that is a breaking change');
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (err) {
    console.error(`sync-icons: ${err.message}`);
    process.exitCode = 2;
  }
}
